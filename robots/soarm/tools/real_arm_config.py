"""Write configs/hardware/soarm101_prompt_depth.json: the part of the real SO-ARM hardware_real config that must match the
simulated twin -- TASK.md overrides (intro v5 + harness prompt profile compact_v1, i.e. the same TASK.md, API docs and
summarised tool results as the sim episodes) and the MoGe-2 depth alignment (support plane height + calibrated table
footprint). Merge it into the arm's hardware config (`--hardware-config`, harness adapters/hardware/episode.py reads
`task_markdown_overrides` and `mono_depth`); re-measure `table_footprint_m` on the real table (it must lie on the
table top; the sim value is the rectangle every simulated table covers).

    python tools/real_arm_config.py [--check]
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
os.environ["MAX_REQUESTS"] = "100"          # the intro states the request budget; the real arm's is 100

from soarm import perception  # noqa: E402
from soarm.episode import task_markdown_overrides  # noqa: E402

PATH = HERE.parent / "configs" / "hardware" / "soarm101_prompt_depth.json"


def fragment() -> dict:
    return {"comment": "Generated by tools/real_arm_config.py: merge into the SO-ARM hardware_real config so the real arm "
                       "presents the sim twin's TASK.md / tool outputs (intro v5, profile compact_v1) and depth alignment. "
                       "Re-measure mono_depth.table_footprint_m on the real table.",
            "task_markdown_overrides": task_markdown_overrides("v5"),
            "mono_depth": {"model": perception.MOGE2_MODEL, "support_plane_z_m": perception.SUPPORT_PLANE_Z_M,
                           "table_footprint_m": perception.TABLE_FOOTPRINT_M}}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the committed file differs")
    a = ap.parse_args()
    text = json.dumps(fragment(), indent=1) + "\n"
    if a.check:
        if PATH.read_text() != text:
            raise SystemExit(f"{PATH} is stale: run tools/real_arm_config.py")
        print("ok")
        return
    PATH.parent.mkdir(parents=True, exist_ok=True)
    PATH.write_text(text)
    print(PATH)


if __name__ == "__main__":
    main()
